/**
 * Voice Vibes — Bot Drawing Library
 *
 * The game's "artist" is a bot. Each word maps to a vector drawing made of
 * strokes in a 1000×600 logical space. The bot reveals the drawing
 * stroke-by-stroke while players guess what it is.
 *
 * Stroke format:
 *   { c: color, s: strokeSize, f: 1|0, p: [[x,y], ...] }
 *   - f=1 → filled shape (fill + optional outline when s>0)
 *   - f=0 → open polyline (stroke only)
 *
 * Fill shapes "pop in" when revealed; line strokes animate progressively.
 */

// ── primitives ──────────────────────────────────────────────────────────────
const N = (c, s, p) => ({ c, s, p, f: 0 });
const F = (c, p) => ({ c, s: 0, p, f: 1 });
const FS = (c, s, p) => ({ c, s, p, f: 1 });

function circle(cx, cy, r, c, s = 0, f = 1, seg = 30) {
  const p = [];
  for (let i = 0; i <= seg; i++) {
    const a = (i / seg) * Math.PI * 2;
    p.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }
  return { c, s, p, f: f ? 1 : 0 };
}

function ellipse(cx, cy, rx, ry, c, s = 0, f = 1, seg = 32) {
  const p = [];
  for (let i = 0; i <= seg; i++) {
    const a = (i / seg) * Math.PI * 2;
    p.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return { c, s, p, f: f ? 1 : 0 };
}

function arc(cx, cy, r, a0, a1, c, s, seg = 22) {
  const p = [];
  for (let i = 0; i <= seg; i++) {
    const a = a0 + ((a1 - a0) * i) / seg;
    p.push([cx + Math.cos(a) * r, cy + Math.sin(a) * r]);
  }
  return { c, s, p, f: 0 };
}

function rect(x, y, w, h, c, s = 0, f = 1) {
  return { c, s, p: [[x, y], [x + w, y], [x + w, y + h], [x, y + h], [x, y]], f: f ? 1 : 0 };
}

function roundedRect(x, y, w, h, r, c, s = 0, f = 1) {
  const p = [
    [x + r, y], [x + w - r, y], [x + w, y + r], [x + w, y + h - r],
    [x + w - r, y + h], [x + r, y + h], [x, y + h - r], [x, y + r],
  ];
  return { c, s, p: [...p, p[0]], f: f ? 1 : 0 };
}

function heart(cx, cy, sc, c, s = 0, f = 1) {
  const p = [];
  for (let i = 0; i <= 44; i++) {
    const t = (i / 44) * Math.PI * 2;
    const x = 16 * Math.sin(t) ** 3;
    const y = 13 * Math.cos(t) - 5 * Math.cos(2 * t) - 2 * Math.cos(3 * t) - Math.cos(4 * t);
    p.push([cx + x * sc, cy - y * sc]);
  }
  return { c, s, p, f: f ? 1 : 0 };
}

function star(cx, cy, r, c, s = 0, f = 1) {
  const p = [];
  for (let i = 0; i < 10; i++) {
    const a = -Math.PI / 2 + (i * Math.PI) / 5;
    const rr = i % 2 ? r * 0.42 : r;
    p.push([cx + Math.cos(a) * rr, cy + Math.sin(a) * rr]);
  }
  p.push(p[0]);
  return { c, s, p, f: f ? 1 : 0 };
}

